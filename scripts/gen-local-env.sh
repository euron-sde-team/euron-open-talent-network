#!/usr/bin/env bash
# Write deploy/compose/.env with random, local-only secrets (once; never overwrites a
# value, never prints one). Delete the file to regenerate. An existing file only gains
# the keys added since it was written (e.g. TALENT_VIEW_HASH_SALT).
set -euo pipefail
f="$(cd "$(dirname "$0")/.." && pwd)/deploy/compose/.env"
rand() { openssl rand -base64 64 | tr -d '/+=\n' | cut -c1-"$1"; }
# 32 random bytes, standard base64 (TOTP_ENCRYPTION_KEY's format).
key32() { openssl rand -base64 32 | tr -d '\n'; }
umask 077

if [[ -f "$f" ]]; then
  added=()
  if ! grep -q '^TALENT_TOTP_ENCRYPTION_KEY=' "$f"; then
    printf 'TALENT_TOTP_ENCRYPTION_KEY=%s\n' "$(key32)" >>"$f"
    added+=(TALENT_TOTP_ENCRYPTION_KEY)
  fi
  if ! grep -q '^TALENT_VIEW_HASH_SALT=' "$f"; then
    printf 'TALENT_VIEW_HASH_SALT=%s\n' "$(rand 32)" >>"$f"
    added+=(TALENT_VIEW_HASH_SALT)
  fi
  if ((${#added[@]})); then
    echo "deploy/compose/.env: added ${added[*]}"
  else
    echo "deploy/compose/.env exists (delete it to regenerate)"
  fi
  exit 0
fi

cat >"$f" <<ENV
# Generated by scripts/gen-local-env.sh. Local only; never commit.
TALENT_JWT_SECRET=$(rand 64)
TALENT_REFRESH_SECRET=$(rand 64)
TALENT_TOTP_ENCRYPTION_KEY=$(key32)
TALENT_VIEW_HASH_SALT=$(rand 32)
TALENT_DEMO_PASSWORD=Demo-$(rand 12)
ENV
echo "wrote deploy/compose/.env"
